-- EPE LAWA — real article engagement for member story covers.
--
-- Adds the only new signal this release needs: a de-duplicated daily view
-- counter. Read time is estimated from the published body text and comment
-- totals come from the existing comments table. Nothing here fabricates a
-- number: when a story has no views, the count is honestly zero.

create table if not exists public.article_views (
  id          bigint generated by default as identity primary key,
  article_id  uuid not null references public.articles(id) on delete cascade,
  -- A random key kept in the reader's browser; it is not an account id, an IP
  -- address or any other personal identifier.
  viewer_key  text not null,
  viewed_on   date not null default ((now() at time zone 'utc')::date),
  created_at  timestamptz not null default now(),
  constraint article_views_viewer_key_format check (viewer_key ~ '^[a-f0-9]{32}$'),
  constraint article_views_one_per_viewer_day unique (article_id, viewer_key, viewed_on)
);

create index if not exists article_views_article_idx
  on public.article_views (article_id, viewed_on desc);

alter table public.article_views enable row level security;
revoke all on table public.article_views from public, anon, authenticated;
-- Reads are only through the aggregate view below; individual viewer keys,
-- even random ones, never leave the database.

create or replace function public.record_article_view(p_article_id uuid, p_viewer_key text)
returns void
language plpgsql
security definer
set search_path = ''
as $$
begin
  if p_article_id is null or p_viewer_key is null or p_viewer_key !~ '^[a-f0-9]{32}$' then
    raise exception using errcode = '22023', message = 'invalid_article_view';
  end if;

  -- Drafts and unpublished articles are never counted.
  if not exists (
    select 1 from public.articles a
    where a.id = p_article_id and a.published_version_id is not null
  ) then
    return;
  end if;

  insert into public.article_views (article_id, viewer_key)
  values (p_article_id, p_viewer_key)
  on conflict (article_id, viewer_key, viewed_on) do nothing;
end;
$$;

revoke all on function public.record_article_view(uuid, text) from public, anon, authenticated;
grant execute on function public.record_article_view(uuid, text) to anon, authenticated;

-- Reading-time estimate (220 words per minute) from the published JSON body.
-- Structural keys are stripped before words are counted, so the estimate does
-- not grow just because the body is stored as rich text.
create or replace function public.estimate_article_read_minutes(p_body jsonb)
returns integer
language sql
immutable
as $$
  select greatest(
    1,
    ceil(
      coalesce(
        array_length(
          regexp_split_to_array(
            nullif(
              btrim(
                regexp_replace(
                  regexp_replace(coalesce(p_body::text, ''), '"(type|text|content|attrs|marks|href|src|alt|caption|credit|level)"\s*:', ' ', 'g'),
                  '[][{}",:]', ' ', 'g'
                )
              ),
              ''
            ),
            '\s+'
          ),
          1
        ),
        0
      ) / 220.0
    )
  )::integer;
$$;

revoke all on function public.estimate_article_read_minutes(jsonb) from public, anon, authenticated;
grant execute on function public.estimate_article_read_minutes(jsonb) to anon, authenticated;

-- Aggregate only: id, slug, total views, visible comment count and read-time
-- estimate for published stories. No viewer keys, no member identities.
create or replace view public.published_article_engagement as
select
  a.id::uuid as article_id,
  a.slug::text as slug,
  (select count(*) from public.article_views av where av.article_id = a.id)::bigint as view_count,
  (select count(*) from public.comments c where c.article_id = a.id and c.state = 'visible')::bigint as comment_count,
  public.estimate_article_read_minutes(v.body) as read_minutes
from public.articles a
join public.article_versions v on v.id = a.published_version_id
where a.published_version_id is not null;

grant select on public.published_article_engagement to anon, authenticated;
